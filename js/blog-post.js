    function initializeComments() {
        const commentForm = document.getElementById('commentForm');
        const commentsData = JSON.parse(localStorage.getItem('blog_comments') || '{}');
        
        commentForm.addEventListener('submit', function(e) {
            e.preventDefault();
            
            const formData = new FormData(this);
            const name = this.querySelector('input[type="text"]').value;
            const email = this.querySelector('input[type="email"]').value;
            const comment = this.querySelector('textarea').value;
            
            // Create comment object
            const newComment = {
                id: Date.now(),
                name: name,
                email: email,
                comment: comment,
                date: new Date().toLocaleDateString('az-AZ'),
                likes: 0,
                postId: postId
            };
            
            // Save to localStorage
            if (!commentsData[postId]) {
                commentsData[postId] = [];
            }
            commentsData[postId].unshift(newComment);
            localStorage.setItem('blog_comments', JSON.stringify(commentsData));
            
            // Add comment to DOM
            addCommentToDOM(newComment);
            
            // Reset form
            this.reset();
            
            // Show success message
            showNotification('Şərhiniz uğurla əlavə edildi!', 'success');
        });
        
        // Load existing comments
        if (commentsData[postId]) {
            commentsData[postId].forEach(comment => {
                addCommentToDOM(comment);
            });
        }
    }
    
    function addCommentToDOM(comment) {
        const commentsList = document.querySelector('.comments-list');
        const commentElement = document.createElement('div');
        commentElement.className = 'comment';
        commentElement.innerHTML = `
            <div class="comment-avatar">
                <img src="assets/images/default-avatar.svg" alt="${comment.name}">
            </div>
            <div class="comment-content">
                <div class="comment-header">
                    <h4>${comment.name}</h4>
                    <span class="comment-date">${comment.date}</span>
                </div>
                <p>${comment.comment}</p>
                <div class="comment-actions">
                    <button class="like-btn" data-comment-id="${comment.id}">
                        <i class="fas fa-thumbs-up"></i> ${comment.likes}
                    </button>
                    <button class="reply-btn">
                        <i class="fas fa-reply"></i> Cavabla
                    </button>
                </div>
            </div>
        `;
        
        commentsList.insertBefore(commentElement, commentsList.firstChild);
        
        // Add like functionality
        const likeBtn = commentElement.querySelector('.like-btn');
        likeBtn.addEventListener('click', function() {
            likeComment(comment.id);
        });
    }
    
    function likeComment(commentId) {
        const commentsData = JSON.parse(localStorage.getItem('blog_comments') || '{}');
        const likedComments = JSON.parse(localStorage.getItem('liked_comments') || '[]');
        
        if (likedComments.includes(commentId)) {
            showNotification('Bu şərhi artıq bəyənmisiniz!', 'warning');
            return;
        }
        
        // Find and update comment
        if (commentsData[postId]) {
            const comment = commentsData[postId].find(c => c.id === commentId);
            if (comment) {
                comment.likes++;
                likedComments.push(commentId);
                
                localStorage.setItem('blog_comments', JSON.stringify(commentsData));
                localStorage.setItem('liked_comments', JSON.stringify(likedComments));
                
                // Update DOM
                const likeBtn = document.querySelector(`[data-comment-id="${commentId}"]`);
                likeBtn.innerHTML = `<i class="fas fa-thumbs-up"></i> ${comment.likes}`;
                
                showNotification('Şərh bəyənildi!', 'success');
            }
        }
    }
    
    function initializeSocialShare() {
        const currentUrl = window.location.href;
        const postTitle = document.getElementById('postTitle').textContent;
        
        window.shareOnFacebook = function() {
            const url = `https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(currentUrl)}`;
            window.open(url, '_blank', 'width=600,height=400');
        };
        
        window.shareOnTwitter = function() {
            const text = `${postTitle} - ${currentUrl}`;
            const url = `https://twitter.com/intent/tweet?text=${encodeURIComponent(text)}`;
            window.open(url, '_blank', 'width=600,height=400');
        };
        
        window.shareOnLinkedIn = function() {
            const url = `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(currentUrl)}`;
            window.open(url, '_blank', 'width=600,height=400');
        };
        
        window.shareOnWhatsApp = function() {
            const text = `${postTitle} - ${currentUrl}`;
            const url = `https://wa.me/?text=${encodeURIComponent(text)}`;
            window.open(url, '_blank');
        };
    }
    
    function initializeReadingProgress() {
        // Create reading progress bar
        const progressBar = document.createElement('div');
        progressBar.className = 'reading-progress';
        progressBar.innerHTML = '<div class="reading-progress-bar"></div>';
        document.body.appendChild(progressBar);
        
        const progressBarFill = progressBar.querySelector('.reading-progress-bar');
        
        window.addEventListener('scroll', function() {
            const article = document.querySelector('.post-content');
            const articleTop = article.offsetTop;
            const articleHeight = article.offsetHeight;
            const windowHeight = window.innerHeight;
            const scrollTop = window.pageYOffset;
            
            const progress = Math.min(100, Math.max(0, 
                ((scrollTop - articleTop + windowHeight) / articleHeight) * 100
            ));
            
            progressBarFill.style.width = progress + '%';
        });
    }
    
    function showNotification(message, type = 'info') {
        // Remove existing notifications
        const existingNotification = document.querySelector('.notification');
        if (existingNotification) {
            existingNotification.remove();
        }
        
        // Create notification element
        const notification = document.createElement('div');
        notification.className = `notification notification-${type}`;
        notification.innerHTML = `
            <div class="notification-content">
                <i class="fas fa-${type === 'success' ? 'check-circle' : type === 'warning' ? 'exclamation-triangle' : 'info-circle'}"></i>
                <span>${message}</span>
                <button class="notification-close">
                    <i class="fas fa-times"></i>
                </button>
            </div>
        `;
        
        // Add to page
        document.body.appendChild(notification);
        
        // Show notification
        setTimeout(() => {
            notification.classList.add('show');
        }, 100);
        
        // Auto hide after 5 seconds
        setTimeout(() => {
            hideNotification(notification);
        }, 5000);
        
        // Close button functionality
        notification.querySelector('.notification-close').addEventListener('click', () => {
            hideNotification(notification);
        });
    }
    
    function hideNotification(notification) {
        notification.classList.remove('show');
        setTimeout(() => {
            if (notification.parentNode) {
                notification.parentNode.removeChild(notification);
            }
        }, 300);
    }
    
